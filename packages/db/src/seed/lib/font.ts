function compile(art: string): number[] {
  const rows = art
    .split('\n')
    .map((line) => line.trim())
    .filter((line) => line.length > 0);

  if (rows.length !== GLYPH_HEIGHT) {
    throw new Error(`Glyph must have ${GLYPH_HEIGHT} rows, found ${rows.length}`);
  }
  return rows.map((row) => {
    if (row.length !== GLYPH_WIDTH) {
      throw new Error(`Glyph row must be ${GLYPH_WIDTH} columns wide, found "${row}"`);
    }
    let bits = 0;
    for (let i = 0; i < GLYPH_WIDTH; i += 1) {
      bits = (bits << 1) | (row[i] === '#' ? 1 : 0);
    }
    return bits;
  });
}

/** char → 7 rows of 5-bit masks, MSB is the leftmost column. */
export const GLYPHS: Record<string, number[]> = Object.fromEntries(
  Object.entries(ART).map(([char, art]) => [char, compile(art)]),
);

// Fallback for anything unmapped — a filled box is unmistakable in output,
// which is better than silently dropping the character.
GLYPHS['?'] = GLYPHS['?'] ?? compile(ART['?']);
